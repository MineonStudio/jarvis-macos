enum ScreenshotTranslationLanguage: String, CaseIterable, Codable, Identifiable, Sendable {
    case simplifiedChinese = "zh-Hans"
    case traditionalChinese = "zh-Hant"
    case english = "en"
    case japanese = "ja"
    case korean = "ko"
    case spanish = "es"

    var id: String {
        rawValue
    }

    var title: String {
        switch self {
        case .simplifiedChinese: "简体中文"
        case .traditionalChinese: "繁體中文"
        case .english: "English"
        case .japanese: "日本語"
        case .korean: "한국어"
        case .spanish: "Español"
        }
    }

    var appleLanguageIdentifier: String {
        switch self {
        case .simplifiedChinese: "zh-Hans"
        case .traditionalChinese: "zh-Hant"
        case .english: "en-US"
        case .japanese: "ja-JP"
        case .korean: "ko-KR"
        case .spanish: "es-ES"
        }
    }

    var localeLanguage: Locale.Language {
        Locale.Language(identifier: appleLanguageIdentifier)
    }

    func matches(_ language: Locale.Language) -> Bool {
        let code = language.languageCode?.identifier.lowercased()
        let script = language.script?.identifier
        switch self {
        case .simplifiedChinese:
            return code == "zh" && (script == nil || script == "Hans")
        case .traditionalChinese:
            return code == "zh" && script == "Hant"
        case .english:
            return code == "en"
        case .japanese:
            return code == "ja"
        case .korean:
            return code == "ko"
        case .spanish:
            return code == "es"
        }
    }
}

enum ScreenshotTranslationConfiguration {
    static let targetLanguageKey = "jarvis.screenshot.translation.target-language"

    static func loadTargetLanguage(
        defaults: UserDefaults = .standard
    ) -> ScreenshotTranslationLanguage {
        ScreenshotTranslationLanguage(
            rawValue: defaults.string(forKey: targetLanguageKey) ?? ""
        ) ?? .simplifiedChinese
    }
}

struct ScreenshotOCRBlock: Equatable, Identifiable, Sendable {
    let id: UUID
    let text: String
    /// Vision's normalized coordinate space converted to a top-left origin.
    /// x/y/width/height are all in the 0...1 range.
    let normalizedBounds: CGRect
    let confidence: Float
    let lineHeight: CGFloat

    init(
        id: UUID,
        text: String,
        normalizedBounds: CGRect,
        confidence: Float,
        lineHeight: CGFloat? = nil
    ) {
        self.id = id
        self.text = text
        self.normalizedBounds = normalizedBounds
        self.confidence = confidence
        self.lineHeight = max(0.001, lineHeight ?? normalizedBounds.height)
    }
}

struct ScreenshotTranslationBlock: Equatable, Identifiable, Sendable {
    let id: UUID
    let sourceText: String
    var translatedText: String
    /// Bounds remain owned by Vision and are never generated by the model.
    let normalizedBounds: CGRect
    let confidence: Float
    let lineHeight: CGFloat

    init(
        id: UUID,
        sourceText: String,
        translatedText: String,
        normalizedBounds: CGRect,
        confidence: Float,
        lineHeight: CGFloat? = nil
    ) {
        self.id = id
        self.sourceText = sourceText
        self.translatedText = translatedText
        self.normalizedBounds = normalizedBounds
        self.confidence = confidence
        self.lineHeight = max(0.001, lineHeight ?? normalizedBounds.height)
    }
}

